function normalizeHeadingLabel(value: string): string {
  return value
    .replace(/[`*_]/g, '')
    .replace(/\s*:+\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function extractHeadingsByLevel(content: string, level: number): string[] {
  const pattern = new RegExp(`^#{${level}}\\s+(.+)$`, 'gim');
  return Array.from(content.matchAll(pattern))
    .map((match) => match[1]?.trim() ?? '')
    .filter((value) => value.length > 0);
}

function getUnsupportedCursorRuleHeadings(content: string, ruleFilename: string): string[] {
  const body = stripLeadingFrontmatter(content);
  const headings = extractHeadingsByLevel(body, 2).map(normalizeHeadingLabel);
  if (headings.length === 0) {
    return [];
  }

  const allowedHeadings =
    ruleFilename === 'project.mdc'
      ? CURSOR_ALLOWED_ROOT_HEADINGS
      : CURSOR_ALLOWED_ADAPTER_HEADINGS[ruleFilename];
  if (!allowedHeadings) {
    return [];
  }

  return headings.filter((heading) => !allowedHeadings.has(heading));
}

function hasCursorCanonicalSourceLink(content: string, ruleFilename: string): boolean {
  const links = getCursorCanonicalDocLinks(ruleFilename);
  if (links.length === 0) {
    return /\.claude\/docs\/[a-z0-9._/-]+\.md/i.test(content);
  }
  const normalized = content.toLowerCase();
  return links.some((link) => normalized.includes(link.toLowerCase()));
}

function hasDuplicateFrontmatterBlockInBody(content: string): boolean {
  const body = stripLeadingFrontmatter(content);
  const yamlFencePattern = /```ya?ml[\t ]*\n[\s\S]*?```/gi;
  for (const match of body.matchAll(yamlFencePattern)) {
    if (/\b(?:description|globs|alwaysApply)\s*:/i.test(match[0] ?? '')) {
      return true;
    }
  }

  const inlineFrontmatterPattern = /(?:^|\n)---\s*\n([\s\S]*?)\n---\s*(?=\n|$)/g;
  for (const match of body.matchAll(inlineFrontmatterPattern)) {
    if (/\b(?:description|globs|alwaysApply)\s*:/i.test(match[1] ?? '')) {
      return true;
    }
  }

  return false;
}

function normalizeLineForOverlap(value: string): string {
  return value
    .replace(/\[[^\]]+\]\(([^)]+)\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/^[-*]\s+/, '')
    .replace(/^#{1,6}\s+/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

function buildComparableLineSet(content: string): Set<string> {
  const body = stripLeadingFrontmatter(content);
  const lines = body
    .split('\n')
    .map(normalizeLineForOverlap)
    .filter((line) => line.length >= 14);
  return new Set(lines);
}

