function buildValidationScoreReport(
  issues: ValidationIssue[],
  context: {
    hasRootDocs: boolean;
    hasMultipleRoots: boolean;
    hasCursorRules: boolean;
  },
): ValidationScoreReport {
  const issueCounts = countIssuesByType(issues);
  const criteria: ValidationScoreCriterion[] = RUBRIC_CRITERIA.map((criterion) => ({
    key: criterion.key,
    label: criterion.label,
    weight: criterion.weight,
    score: buildCriterionScore(criterion.key, issueCounts),
  }));

  const weightSum = criteria.reduce((sum, criterion) => sum + criterion.weight, 0) || 1;
  const weightedScore =
    criteria.reduce((sum, criterion) => sum + criterion.score * criterion.weight, 0) / weightSum;
  const overall = roundScore(weightedScore);

  return {
    overall,
    band: getRubricBand(overall),
    criteria,
    checklist: buildValidationChecklist(issues, context),
  };
}

function validateRootStructure(filePath: string, content: string): ValidationIssue[] {
  const target = getRootTarget(filePath);
  if (!target) return [];

  const issues: ValidationIssue[] = [];
  const contract = getRootDocContract(target);
  const nonEmptyLines = content
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  for (const heading of contract.requiredHeadings) {
    const headingRegex = new RegExp(`^\\s*#{1,6}\\s*${heading}\\s*:?\\s*$`, 'im');
    if (!headingRegex.test(content)) {
      issues.push({
        file: filePath,
        line: 1,
        type: 'invalid-root-structure',
        message: `Missing required heading "${heading}" in root document.`,
        reference: heading,
      });
    }
  }

  for (const disallowedPattern of contract.disallowedPatterns) {
    if (disallowedPattern.test(content)) {
      issues.push({
        file: filePath,
        line: 1,
        type: 'invalid-root-structure',
        message: 'Root document contains generation/process-log style text.',
        reference: disallowedPattern.source,
      });
    }
  }

  if (nonEmptyLines.length < contract.minNonEmptyLines) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'low-information-density',
      message: `Root document is too short (${nonEmptyLines.length} lines, expected at least ${contract.minNonEmptyLines}).`,
      reference: String(nonEmptyLines.length),
    });
  }

  if (contract.maxNonEmptyLines && nonEmptyLines.length > contract.maxNonEmptyLines) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'low-information-density',
      message: `Root document is too long (${nonEmptyLines.length} lines, expected at most ${contract.maxNonEmptyLines}).`,
      reference: String(nonEmptyLines.length),
    });
  }

  if (contract.maxBytes) {
    const contentBytes = Buffer.byteLength(content, 'utf8');
    if (contentBytes > contract.maxBytes) {
      issues.push({
        file: filePath,
        line: 1,
        type: 'low-information-density',
        message: `Root document exceeds byte budget (${contentBytes} bytes, expected at most ${contract.maxBytes}).`,
        reference: String(contentBytes),
      });
    }
  }

  const warningSection = getCriticalWarningsSection(content);
  if (!warningSection) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'missing-critical-warning',
      message: 'Missing "Critical Warnings" section in root document.',
      reference: 'Critical Warnings',
    });
    return issues;
  }

  const warningTopics = detectWarningTopics(warningSection);
  for (const requiredTopic of contract.requiredWarningTopics) {
    if (!warningTopics.has(requiredTopic)) {
      issues.push({
        file: filePath,
        line: 1,
        type: 'missing-critical-warning',
        message: `Missing warning topic "${requiredTopic}" in Critical Warnings section.`,
        reference: requiredTopic,
      });
    }
  }

  return issues;
}

function validateCursorFrontmatter(filePath: string, content: string): ValidationIssue[] {
  if (!filePath.replace(/\\/g, '/').endsWith('.mdc')) {
    return [];
  }

  const issues: ValidationIssue[] = [];
  const frontmatter = extractCursorFrontmatter(content);
  if (!frontmatter) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message:
        'Cursor rule file is missing YAML frontmatter. Add description/globs/alwaysApply fields.',
      reference: 'cursor-frontmatter',
    });
    return issues;
  }

  const descriptionValue = extractFrontmatterField(frontmatter, 'description');
  const globsValue = extractFrontmatterField(frontmatter, 'globs');
  const alwaysApplyValue = extractFrontmatterField(frontmatter, 'alwaysApply');

  if (descriptionValue === null) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'Cursor frontmatter must include "description".',
      reference: 'cursor-frontmatter:description',
    });
  }

  if (globsValue === null) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'Cursor frontmatter must include "globs".',
      reference: 'cursor-frontmatter:globs',
    });
  }

  if (alwaysApplyValue === null) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'Cursor frontmatter must include "alwaysApply".',
      reference: 'cursor-frontmatter:alwaysApply',
    });
    return issues;
  }

  const normalizedAlwaysApply = alwaysApplyValue.toLowerCase();
  if (normalizedAlwaysApply !== 'true' && normalizedAlwaysApply !== 'false') {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'Cursor frontmatter "alwaysApply" must be a boolean (true/false).',
      reference: `cursor-frontmatter:alwaysApply=${alwaysApplyValue}`,
    });
    return issues;
  }

  const alwaysApply = normalizedAlwaysApply === 'true';
  if (alwaysApply && hasNonEmptyGlobValue(globsValue)) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'Cursor rule with alwaysApply=true must keep globs empty.',
      reference: 'cursor-frontmatter:alwaysApply+globs',
    });
  }

  const normalizedPath = filePath.replace(/\\/g, '/');
  if (normalizedPath.endsWith('/.cursor/rules/project.mdc') && !alwaysApply) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: 'project.mdc must be always-on (alwaysApply: true).',
      reference: 'cursor-frontmatter:project-alwaysApply',
    });
  }

  return issues;
}

function validateCursorRuleAdapterQuality(filePath: string, content: string): ValidationIssue[] {
  if (!isCursorRuleFile(filePath)) {
    return [];
  }

  const issues: ValidationIssue[] = [];
  const ruleFilename = getCursorRuleFilename(filePath);
  const nonEmptyLines = countNonEmptyLines(stripLeadingFrontmatter(content));
  const maxLines =
    ruleFilename === 'project.mdc'
      ? CURSOR_ROOT_DOC_MAX_NON_EMPTY_LINES
      : CURSOR_ADAPTER_DOC_MAX_NON_EMPTY_LINES;

  if (nonEmptyLines > maxLines) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'low-information-density',
      message: `Cursor rule "${ruleFilename}" is too long for a scoped adapter (${nonEmptyLines} lines, expected at most ${maxLines}).`,
      reference: `cursor-rule-size:${ruleFilename}`,
    });
  }

  if (ruleFilename !== 'project.mdc' && !hasCursorCanonicalSourceLink(content, ruleFilename)) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'target-inconsistency',
      message: `Cursor adapter "${ruleFilename}" is missing link(s) to canonical shared docs under .claude/docs/.`,
      reference: `cursor-adapter:canonical-link:${ruleFilename}`,
    });
  }

  if (hasDuplicateFrontmatterBlockInBody(content)) {
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message:
        'Cursor rule body must not duplicate frontmatter blocks. Keep description/globs/alwaysApply only in the leading YAML frontmatter.',
      reference: `cursor-frontmatter:body-duplicate:${ruleFilename}`,
    });
  }

  const unsupportedHeadings = getUnsupportedCursorRuleHeadings(content, ruleFilename);
  if (unsupportedHeadings.length > 0) {
    const sample = unsupportedHeadings.slice(0, 3).join(', ');
    issues.push({
      file: filePath,
      line: 1,
      type: 'invalid-root-structure',
      message: `Cursor rule "${ruleFilename}" contains unsupported section headings for a thin adapter: ${sample}.`,
      reference:
        ruleFilename === 'project.mdc'
          ? `cursor-root:unsupported-heading:${sample}`
          : `cursor-adapter:unsupported-heading:${ruleFilename}:${sample}`,
    });
  }

  return issues;
}

