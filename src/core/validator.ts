async function validateQualityGateConsistency(projectRoot: string): Promise<ValidationIssue[]> {
  const issues: ValidationIssue[] = [];
  const gateStatusByDoc = new Map<string, Map<string, 'required' | 'optional'>>();

  for (const relativePath of ROOT_DOC_PATHS) {
    const fullPath = path.join(projectRoot, relativePath);
    const content = await readFileSafe(fullPath);
    if (!content) continue;
    const section = getQualityGatesSection(content);
    if (!section) continue;
    gateStatusByDoc.set(relativePath, detectQualityGateStatuses(section));
  }

  if (gateStatusByDoc.size < 2) {
    return issues;
  }

  const allGates = new Set<string>();
  for (const statuses of gateStatusByDoc.values()) {
    for (const gate of statuses.keys()) {
      allGates.add(gate);
    }
  }

  for (const gate of allGates) {
    const statusesForGate: Array<{ docPath: string; status: 'required' | 'optional' }> = [];
    for (const [docPath, statuses] of gateStatusByDoc.entries()) {
      const status = statuses.get(gate);
      if (status) {
        statusesForGate.push({ docPath, status });
      }
    }

    const uniqueStatuses = new Set(statusesForGate.map((entry) => entry.status));
    if (uniqueStatuses.size <= 1) continue;

    for (const entry of statusesForGate) {
      issues.push({
        file: path.join(projectRoot, entry.docPath),
        line: 1,
        type: 'inconsistent-quality-gate',
        message: `Quality gate policy for "${gate}" is inconsistent across targets (${entry.status}).`,
        reference: `${gate}:${entry.status}`,
      });
    }
  }

  return issues;
}

function extractCommands(content: string): { line: number; command: string }[] {
  const results: { line: number; command: string }[] = [];
  const codeBlocks = content.matchAll(CODE_BLOCK_PATTERN);

  for (const match of codeBlocks) {
    const blockStart = content.slice(0, match.index).split('\n').length;
    const lines = match[0].split('\n').slice(1, -1);

    for (let i = 0; i < lines.length; i++) {
      const trimmed = lines[i].trim();
      if (COMMAND_PREFIXES.some((p) => trimmed.startsWith(p))) {
        results.push({ line: blockStart + i, command: trimmed });
      }
    }
  }
  return results;
}

function normalizeLinkTarget(rawTarget: string): string {
  const trimmed = rawTarget.trim();
  const unwrapped =
    trimmed.startsWith('<') && trimmed.endsWith('>') ? trimmed.slice(1, -1) : trimmed;
  const firstToken = unwrapped.split(/\s+/)[0] ?? '';
  const withoutHash = firstToken.split('#')[0] ?? '';
  const withoutQuery = withoutHash.split('?')[0] ?? '';
  return withoutQuery.trim();
}

function extractPaths(content: string): { line: number; path: string }[] {
  const results: { line: number; path: string }[] = [];
  const seen = new Set<string>();
  const lines = content.split('\n');

  for (let i = 0; i < lines.length; i++) {
    const inlineCodes = lines[i].matchAll(INLINE_CODE_PATTERN);
    for (const match of inlineCodes) {
      const code = match[1];
      const pathMatches = code.matchAll(PATH_PATTERN);
      for (const pm of pathMatches) {
        const candidate = pm[1];
        const key = `${i + 1}:${candidate}`;
        if (!seen.has(key)) {
          seen.add(key);
          results.push({ line: i + 1, path: candidate });
        }
      }
    }

    const markdownLinks = lines[i].matchAll(MARKDOWN_LINK_PATTERN);
    for (const match of markdownLinks) {
      const candidate = normalizeLinkTarget(match[1] ?? '');
      if (!candidate) continue;
      const key = `${i + 1}:${candidate}`;
      if (!seen.has(key)) {
        seen.add(key);
        results.push({ line: i + 1, path: candidate });
      }
    }
  }

  return results;
}

async function pathExistsFromDoc(
  projectRoot: string,
  docFile: string,
  refPath: string,
): Promise<boolean> {
  const normalized = refPath.replace(/^"|"$/g, '').trim();
  const candidates = new Set<string>();
  const docDir = path.dirname(docFile);

  if (normalized.startsWith('/')) {
    candidates.add(path.join(projectRoot, normalized.slice(1)));
  }

  candidates.add(path.resolve(docDir, normalized));
  candidates.add(path.resolve(projectRoot, normalized));

  for (const candidate of candidates) {
    if (await fileExists(candidate)) {
      return true;
    }
  }

  return false;
}

function isLikelyApiEndpointPath(refPath: string): boolean {
  if (!refPath.startsWith('/')) return false;
  if (refPath === '/') return false;

  if (ABSOLUTE_FILESYSTEM_PREFIXES.some((prefix) => refPath.startsWith(prefix))) {
    return false;
  }

  const normalized = refPath.replace(/\/+$/, '');
  const baseName = path.posix.basename(normalized);
  const hasExtension = /\.[A-Za-z0-9]+$/.test(baseName);
  if (hasExtension) {
    return false;
  }

  return true;
}

function normalizeDocReferencePath(refPath: string): string {
  return refPath
    .trim()
    .replace(/^['"`]|['"`]$/g, '')
    .replace(/^\.\//, '');
}

function isCursorCanonicalSharedDocReference(filePath: string, refPath: string): boolean {
  const normalizedFile = filePath.replace(/\\/g, '/');
  if (!normalizedFile.includes('/.cursor/rules/')) {
    return false;
  }
  const normalizedRef = normalizeDocReferencePath(refPath);
  return /^\.claude\/docs\/[a-z0-9._/-]+\.md$/i.test(normalizedRef);
}

const sharedDocsPresenceCache = new Map<string, boolean>();

async function hasAnySharedCanonicalDocs(projectRoot: string): Promise<boolean> {
  const cacheKey = path.resolve(projectRoot);
  const cached = sharedDocsPresenceCache.get(cacheKey);
  if (cached !== undefined) {
    return cached;
  }

  for (const rootDoc of SHARED_ROOT_DOCS) {
    if (await fileExists(path.join(projectRoot, rootDoc))) {
      sharedDocsPresenceCache.set(cacheKey, true);
      return true;
    }
  }

  for (const filename of GENERATED_CLAUDE_DOCS) {
    if (await fileExists(path.join(projectRoot, '.claude', 'docs', filename))) {
      sharedDocsPresenceCache.set(cacheKey, true);
      return true;
    }
  }

  sharedDocsPresenceCache.set(cacheKey, false);
  return false;
}

export async function validateFile(
  filePath: string,
  projectRoot: string,
  scripts: Record<string, string>,
): Promise<ValidationIssue[]> {
  const content = await readFileSafe(filePath);
  if (!content) return [];

  const issues: ValidationIssue[] = [
    ...validateCursorFrontmatter(filePath, content),
    ...validateCursorRuleAdapterQuality(filePath, content),
  ];
  const commands = extractCommands(content);
  const paths = extractPaths(content);

  for (const { line, command } of commands) {
    const parts = command.split(/\s+/);
    const runner = parts[0];
    const scriptName = parts[1] === 'run' ? parts[2] : parts[1];

    if (runner && ['npm', 'yarn', 'pnpm', 'bun'].includes(runner) && scriptName) {
      if (
        parts[1] === 'run' ||
        !['install', 'init', 'create', 'exec', 'dlx', 'i'].includes(parts[1])
      ) {
        if (!scripts[scriptName]) {
          issues.push({
            file: filePath,
            line,
            type: 'missing-command',
            message: `Script "${scriptName}" not found in package.json`,
            reference: command,
          });
        }
      }
    }
  }

  for (const { line, path: refPath } of paths) {
    if (
      refPath.startsWith('http') ||
      refPath.startsWith('#') ||
      refPath.startsWith('mailto:') ||
      isLikelyApiEndpointPath(refPath)
    ) {
      continue;
    }

    if (!(await pathExistsFromDoc(projectRoot, filePath, refPath))) {
      if (
        isCursorCanonicalSharedDocReference(filePath, refPath) &&
        !(await hasAnySharedCanonicalDocs(projectRoot))
      ) {
        continue;
      }
      issues.push({
        file: filePath,
        line,
        type: 'missing-path',
        message: `Path "${refPath}" does not exist`,
        reference: refPath,
      });
    }
  }

  return issues;
}

export async function validateProject(
  projectRoot: string,
  scripts: Record<string, string>,
): Promise<ValidationResult> {
  const docPaths = ['CLAUDE.md', 'AGENTS.md', '.cursor/rules', '.claude/docs'];

  const allIssues: ValidationIssue[] = [];

  for (const docPath of docPaths) {
    const full = path.join(projectRoot, docPath);
    try {
      const stat = await fs.stat(full);
      if (stat.isDirectory()) {
        const entries = await fs.readdir(full);
        for (const entry of entries) {
          if (docPath === '.claude/docs' && !GENERATED_CLAUDE_DOCS.has(entry)) {
            continue;
          }
          if (entry.endsWith('.md') || entry.endsWith('.mdc')) {
            const entryPath = path.join(full, entry);
            allIssues.push(...(await validateFile(entryPath, projectRoot, scripts)));
            if (entry === 'project.mdc') {
              allIssues.push(
                ...validateRootStructure(entryPath, (await readFileSafe(entryPath)) ?? ''),
              );
            }
          }
        }
      } else {
        allIssues.push(...(await validateFile(full, projectRoot, scripts)));
        allIssues.push(...validateRootStructure(full, (await readFileSafe(full)) ?? ''));
      }
    } catch {
      // File/dir doesn't exist, skip
    }
  }

  allIssues.push(...(await validateRootDocsConsistency(projectRoot)));
  allIssues.push(...(await validateQualityGateConsistency(projectRoot)));
  allIssues.push(...(await validateCrossTargetCommandParity(projectRoot, scripts)));
  allIssues.push(...(await validateClaudeCodexRootParity(projectRoot)));
  allIssues.push(...(await validateDocsAgainstProjectFacts(projectRoot)));
  allIssues.push(...(await validateCrossTargetFactConsistency(projectRoot, scripts)));
  allIssues.push(...(await validateCursorCanonicalOverlap(projectRoot)));
  allIssues.push(...(await validateStaleManagedFiles(projectRoot)));

  const errors = allIssues.filter(
    (i) => i.type === 'missing-command' || i.type === 'invalid-root-structure',
  );
  const warnings = allIssues.filter(
    (i) => i.type !== 'missing-command' && i.type !== 'invalid-root-structure',
  );
  const rootDocs = await readRootDocs(projectRoot);
  const score = buildValidationScoreReport(allIssues, {
    hasRootDocs: rootDocs.size > 0,
    hasMultipleRoots: rootDocs.size > 1,
    hasCursorRules: await fileExists(path.join(projectRoot, '.cursor/rules/project.mdc')),
  });

  return {
    valid: errors.length === 0,
    errors,
    warnings,
    score,
  };
}
