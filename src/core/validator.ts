function detectWarningTopics(content: string): Set<string> {
  const topics = new Set<string>();
  for (const [topic, pattern] of Object.entries(WARNING_TOPIC_PATTERNS)) {
    if (pattern.test(content)) {
      topics.add(topic);
    }
  }
  return topics;
}

function detectQualityGateStatuses(section: string): Map<string, 'required' | 'optional'> {
  const statuses = new Map<string, 'required' | 'optional'>();
  const lines = section
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

  for (const line of lines) {
    const optional = OPTIONAL_GATE_PATTERN.test(line);
    for (const [gate, pattern] of Object.entries(QUALITY_GATE_PATTERNS)) {
      if (!pattern.test(line)) continue;
      const previous = statuses.get(gate);
      const next: 'required' | 'optional' = optional ? 'optional' : 'required';
      if (!previous || previous === 'optional') {
        statuses.set(gate, next);
      }
      if (previous === 'required' && next === 'optional') {
        statuses.set(gate, 'required');
      }
    }
  }

  return statuses;
}

function clampScore(value: number): number {
  if (!Number.isFinite(value)) return 0;
  if (value < 0) return 0;
  if (value > 10) return 10;
  return value;
}

function roundScore(value: number): number {
  return Math.round(value * 10) / 10;
}

function getRubricBand(overall: number): ValidationScoreBand {
  if (overall < 4) return 'fail';
  if (overall < 7) return 'acceptable';
  if (overall < 9) return 'good';
  return 'excellent';
}

function countIssuesByType(issues: ValidationIssue[]): Map<ValidationIssue['type'], number> {
  const counts = new Map<ValidationIssue['type'], number>();
  for (const issue of issues) {
    counts.set(issue.type, (counts.get(issue.type) ?? 0) + 1);
  }
  return counts;
}

function buildCriterionScore(
  key: ValidationScoreCriterionKey,
  issueCounts: Map<ValidationIssue['type'], number>,
): number {
  const penaltyRules = RUBRIC_PENALTY_RULES[key];
  let deduction = 0;

  for (const [issueType, count] of issueCounts.entries()) {
    const penaltyWeight = penaltyRules[issueType];
    if (!penaltyWeight || count <= 0) continue;
    const severityMultiplier = ISSUE_SEVERITY_MULTIPLIER[issueType] ?? 0.65;
    deduction += penaltyWeight * Math.log2(1 + count) * severityMultiplier;
  }

  return roundScore(clampScore(10 - deduction));
}

function hasIssueByType(issues: ValidationIssue[], type: ValidationIssue['type']): boolean {
  return issues.some((issue) => issue.type === type);
}

function hasIssueByReferencePrefix(issues: ValidationIssue[], prefix: string): boolean {
  return issues.some((issue) => issue.reference.startsWith(prefix));
}

function hasIssueByReference(issues: ValidationIssue[], reference: string): boolean {
  return issues.some((issue) => issue.reference === reference);
}

function hasRootSizeIssue(issues: ValidationIssue[]): boolean {
  return issues.some(
    (issue) =>
      issue.type === 'low-information-density' &&
      (issue.message.includes('too long') || issue.message.includes('byte budget')),
  );
}

function toChecklistStatus(
  evaluated: boolean,
  passing: boolean,
): ValidationChecklistItem['status'] {
  if (!evaluated) return 'unknown';
  return passing ? 'pass' : 'fail';
}

