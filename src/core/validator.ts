function getRootTarget(filePath: string): 'claude' | 'codex' | 'cursor' | null {
  const normalized = filePath.replace(/\\/g, '/');
  if (normalized.endsWith('CLAUDE.md')) return 'claude';
  if (normalized.endsWith('AGENTS.md')) return 'codex';
  if (normalized.endsWith('.cursor/rules/project.mdc')) return 'cursor';
  return null;
}

function normalizeConfiguredTargets(rawTargets: unknown): Target[] {
  if (!Array.isArray(rawTargets)) return [];
  const values = rawTargets.map((target) => String(target));
  try {
    return normalizeTargets(values, 'llmdocs.config.json targets');
  } catch {
    return [];
  }
}

function getSectionContent(content: string, heading: string): string | null {
  const headingMatch = new RegExp(`^#{1,6}\\s*${heading}\\s*:?\\s*$`, 'im').exec(content);
  if (!headingMatch || headingMatch.index === undefined) {
    return null;
  }

  const fromHeading = content.slice(headingMatch.index + headingMatch[0].length);
  const nextHeadingIndex = fromHeading.search(/\n#{1,6}\s+/);
  if (nextHeadingIndex < 0) {
    return fromHeading.trim();
  }
  return fromHeading.slice(0, nextHeadingIndex).trim();
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function extractCursorFrontmatter(content: string): string | null {
  const normalized = content.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\s*\n([\s\S]*?)\n---\s*(?:\n|$)/);
  return match?.[1] ?? null;
}

function extractFrontmatterField(frontmatter: string, fieldName: string): string | null {
  const fieldPattern = new RegExp(`^\\s*${escapeRegExp(fieldName)}\\s*:(.*)$`, 'i');
  for (const line of frontmatter.split('\n')) {
    const match = line.match(fieldPattern);
    if (!match) continue;
    return (match[1] ?? '').trim();
  }
  return null;
}

function hasNonEmptyGlobValue(globsValue: string | null): boolean {
  if (!globsValue) return false;
  const normalized = globsValue.replace(/['"`]/g, '').trim();
  if (!normalized) return false;
  if (normalized === '[]') return false;
  return true;
}

function stripLeadingFrontmatter(content: string): string {
  const normalized = content.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\s*\n[\s\S]*?\n---\s*(?:\n|$)/);
  if (!match) return normalized;
  return normalized.slice(match[0].length);
}

